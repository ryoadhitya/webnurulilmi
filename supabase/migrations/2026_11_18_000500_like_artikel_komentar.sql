/* ==========================================================================
   MIGRASI 000500 — LIKE ARTIKEL, LIKE KOMENTAR, DAN TANGGAL PUBLIKASI
   --------------------------------------------------------------------------
   Tujuan:
     1. Tabel article_likes: menyimpan like artikel per pengunjung anonim.
        Unik per (article_id, visitor_id) supaya satu pengunjung tidak bisa
        membuat like berulang pada artikel yang sama.
     2. Tabel comment_likes: sama seperti di atas, untuk like pada komentar.
     3. RPC toggle_article_like / get_article_like: satu-satunya jalan untuk
        membaca dan mengubah like, lewat SECURITY DEFINER. Pengunjung tidak
        bisa INSERT/UPDATE/DELETE langsung ke tabel like karena tidak ada
        policy RLS untuk itu.
     4. RPC toggle_comment_like / get_comment_likes: padanan untuk komentar.
     5. Tabel like_rate_limits: rate limit per IP (60 aksi like per jam)
        supaya satu jaringan tidak bisa dipakai untuk like massal.
     6. articles.published_at sudah ada sejak migrasi awal dan sekarang
        dipakai sebagai TANGGAL PUBLIKASI yang dipilih admin, bukan lagi
        "waktu tayang otomatis". Tidak ada kolom baru, hanya indeks
        pendukung untuk urutan kronologis.

   Yang TIDAK diubah:
     - Struktur tabel articles, comments, dan seluruh tabel lain.
     - Baris data yang sudah ada (tidak ada UPDATE/DELETE pada artikel,
       komentar, dan media).
     - Policy RLS komentar dan mekanisme moderasi admin.
     - Sistem login admin dan peran (role/permission).

   Semua pernyataan aman dijalankan berulang kali.
   ========================================================================== */

-- ---------------------------------------------------------------------------
--  1. TABEL LIKE
-- ---------------------------------------------------------------------------

create table if not exists public.article_likes (
  id         bigint generated by default as identity primary key,
  article_id bigint not null references public.articles(id) on delete cascade,
  -- Identiitas anonim pengunjung: UUID acak dibuat di browser dan disimpan
  -- di localStorage. Tidak berisi data pribadi.
  visitor_id text not null,
  -- Hash IP untuk rate limit anti-penyalahgunaan (IP mentah tidak disimpan).
  ip_hash    text,
  created_at timestamptz not null default now(),
  constraint article_likes_unique unique (article_id, visitor_id)
);

create index if not exists article_likes_article_id_idx on public.article_likes(article_id);
create index if not exists article_likes_visitor_id_idx on public.article_likes(visitor_id);
create index if not exists article_likes_ip_created_idx on public.article_likes(ip_hash, created_at desc);

create table if not exists public.comment_likes (
  id         bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id) on delete cascade,
  visitor_id text not null,
  ip_hash    text,
  created_at timestamptz not null default now(),
  constraint comment_likes_unique unique (comment_id, visitor_id)
);

create index if not exists comment_likes_comment_id_idx on public.comment_likes(comment_id);
create index if not exists comment_likes_visitor_id_idx on public.comment_likes(visitor_id);

-- Rate limit aksi like per IP (sama pola seperti comment_rate_limits).
create table if not exists public.like_rate_limits (
  id         bigint generated by default as identity primary key,
  ip_hash    text not null,
  created_at timestamptz not null default now()
);

create index if not exists like_rate_limits_ip_created_idx
  on public.like_rate_limits(ip_hash, created_at desc);

-- ---------------------------------------------------------------------------
--  2. FUNGSI BANTU
-- ---------------------------------------------------------------------------

-- IP klien (dibaca dari header proxy Supabase). Sama seperti versi di
-- schema.sql, ditulis ulang supaya migrasi ini mandiri.
create or replace function public.client_ip()
returns text
language sql
stable
as $$
  select nullif(
    split_part(
      coalesce(
        current_setting('request.headers', true)::json ->> 'x-forwarded-for',
        current_setting('request.headers', true)::json ->> 'x-real-ip',
        ''
      ),
      ',', 1
    ),
    ''
  );
$$;

revoke all on function public.client_ip() from public;
grant execute on function public.client_ip() to anon, authenticated;

-- Hash IP untuk rate limit (SHA-256 + salt statis, sama seperti komentar).
create or replace function public.rate_limit_hash()
returns text
language sql
stable
as $$
  select encode(
    extensions.digest(coalesce(public.client_ip(), 'unknown') || 'ypi-nurul-ilmi', 'sha256'),
    'hex'
  );
$$;

revoke all on function public.rate_limit_hash() from public;
grant execute on function public.rate_limit_hash() to anon, authenticated;

-- Validasi identitas anonim pengunjung: harus UUID v4 (huruf kecil).
create or replace function public.normalize_visitor_id(p_visitor_id text)
returns text
language plpgsql
immutable
as $$
declare
  v text := lower(trim(coalesce(p_visitor_id, '')));
begin
  if v !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    return null;
  end if;

  return v;
end;
$$;

revoke all on function public.normalize_visitor_id(text) from public;
grant execute on function public.normalize_visitor_id(text) to anon, authenticated;

-- ---------------------------------------------------------------------------
--  3. RPC LIKE ARTIKEL
-- ---------------------------------------------------------------------------

-- Status like satu artikel untuk satu pengunjung + jumlah like total.
create or replace function public.get_article_like(
  p_article_id bigint,
  p_visitor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_visitor text := public.normalize_visitor_id(p_visitor_id);
  v_liked   boolean := false;
  v_count   bigint := 0;
begin
  select count(*) into v_count
    from public.article_likes
   where article_id = p_article_id;

  if v_visitor is not null then
    select exists (
      select 1 from public.article_likes
       where article_id = p_article_id
         and visitor_id = v_visitor
    ) into v_liked;
  end if;

  return jsonb_build_object(
    'liked', v_liked,
    'count', v_count,
    'visitor_id', coalesce(v_visitor, '')
  );
end;
$$;

revoke all on function public.get_article_like(bigint, text) from public;
grant execute on function public.get_article_like(bigint, text) to anon, authenticated;

-- Tambah atau batalkan like artikel. Mengembalikan status baru.
create or replace function public.toggle_article_like(
  p_article_id bigint,
  p_visitor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_visitor text := public.normalize_visitor_id(p_visitor_id);
  v_hash    text := public.rate_limit_hash();
  v_deleted integer := 0;
  v_liked   boolean := false;
  v_count   bigint := 0;
begin
  if v_visitor is null then
    raise exception 'identitas pengunjung tidak valid';
  end if;

  -- Artikel harus published.
  if not exists (select 1 from public.articles
                  where id = p_article_id and status = 'published') then
    raise exception 'artikel tidak ditemukan';
  end if;

  -- Rate limit: maksimal 60 aksi like per jam per IP.
  if (select count(*) from public.like_rate_limits
        where ip_hash = v_hash
          and created_at > now() - interval '1 hour') >= 60 then
    raise exception 'terlalu sering';
  end if;

  -- Batalkan like bila ada.
  delete from public.article_likes
   where article_id = p_article_id
     and visitor_id = v_visitor;

  get diagnostics v_deleted = row_count;

  if v_deleted = 0 then
    -- Tambah like. Constraint unik mencegah dobel ketika ada dua request
    -- bersamaan dari pengunjung yang sama.
    insert into public.article_likes (article_id, visitor_id, ip_hash, created_at)
    values (p_article_id, v_visitor, v_hash, now())
    on conflict (article_id, visitor_id) do nothing;

    v_liked := true;
  end if;

  insert into public.like_rate_limits (ip_hash, created_at) values (v_hash, now());

  select count(*) into v_count
    from public.article_likes
   where article_id = p_article_id;

  return jsonb_build_object(
    'liked', v_liked,
    'count', v_count,
    'visitor_id', v_visitor
  );
end;
$$;

revoke all on function public.toggle_article_like(bigint, text) from public;
grant execute on function public.toggle_article_like(bigint, text) to anon, authenticated;

-- ---------------------------------------------------------------------------
--  4. RPC LIKE KOMENTAR
-- ---------------------------------------------------------------------------

-- Status like + jumlah like untuk seluruh komentar satu artikel.
create or replace function public.get_comment_likes(
  p_article_id bigint,
  p_visitor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_visitor text := public.normalize_visitor_id(p_visitor_id);
  v_result  jsonb := '{}'::jsonb;
begin
  select coalesce(jsonb_object_agg(
           c.id::text,
           jsonb_build_object(
             'liked', case
                        when v_visitor is not null and exists (
                          select 1 from public.comment_likes cl
                           where cl.comment_id = c.id and cl.visitor_id = v_visitor
                        ) then true
                        else false
                      end,
             'count', (select count(*) from public.comment_likes cl2 where cl2.comment_id = c.id)
           )
         ), '{}'::jsonb)
    into v_result
    from public.comments c
   where c.article_id = p_article_id
     and c.status = 'published';

  return v_result;
end;
$$;

revoke all on function public.get_comment_likes(bigint, text) from public;
grant execute on function public.get_comment_likes(bigint, text) to anon, authenticated;

-- Tambah atau batalkan like satu komentar.
create or replace function public.toggle_comment_like(
  p_comment_id bigint,
  p_visitor_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_visitor text := public.normalize_visitor_id(p_visitor_id);
  v_hash    text := public.rate_limit_hash();
  v_deleted integer := 0;
  v_liked   boolean := false;
  v_count   bigint := 0;
