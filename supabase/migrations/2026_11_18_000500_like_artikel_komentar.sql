    raise exception 'terlalu sering';
  end if;

  delete from public.comment_likes
   where comment_id = p_comment_id
     and visitor_id = v_visitor;

  get diagnostics v_deleted = row_count;

  if v_deleted = 0 then
    insert into public.comment_likes (comment_id, visitor_id, ip_hash, created_at)
    values (p_comment_id, v_visitor, v_hash, now())
    on conflict (comment_id, visitor_id) do nothing;

    v_liked := true;
  end if;

  insert into public.like_rate_limits (ip_hash, created_at) values (v_hash, now());

  select count(*) into v_count
    from public.comment_likes
   where comment_id = p_comment_id;

  return jsonb_build_object(
    'liked', v_liked,
    'count', v_count,
    'visitor_id', v_visitor
  );
end;
$$;

revoke all on function public.toggle_comment_like(bigint, text) from public;
grant execute on function public.toggle_comment_like(bigint, text) to anon, authenticated;

-- ---------------------------------------------------------------------------
--  5. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------------
-- Tabel like tidak punya policy INSERT/UPDATE/DELETE untuk anon maupun
-- authenticated: satu-satunya jalan adalah RPC SECURITY DEFINER di atas.
-- Karena tidak ada policy SELECT pun, PostgREST tidak bisa membacakan
-- tabel ini langsung (termasuk visitor_id milik orang lain).

alter table public.article_likes enable row level security;
alter table public.comment_likes enable row level security;
alter table public.like_rate_limits enable row level security;

-- ---------------------------------------------------------------------------
--  6. TANGGAL PUBLIKASI ARTIKEL
-- ---------------------------------------------------------------------------
-- published_at sudah ada dan kini menjadi tanggal publikasi yang dipilih
-- admin. Yang ditambahkan hanya indeks pendukung untuk urutan kronologis.

create index if not exists articles_published_at_idx on public.articles(published_at desc);
create index if not exists articles_status_published_at_idx
  on public.articles(status, published_at desc);
